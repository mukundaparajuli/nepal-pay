import { parseArgs } from 'node:util'
import { PAYMENT_METHODS, type PaymentMethod } from '@nepal-payments/core'
import {
  DEFAULT_INIT_GATEWAYS,
  GATEWAY_DESCRIPTORS,
  parseGatewayList,
} from '../gateways.js'
import type { CliContext } from '../types.js'

export const INIT_USAGE = `Usage: npay init [options]

Write a .env.example template listing the environment variables the CLI
understands for each gateway. Copy it to .env and fill in real values; the
file contains placeholders only — never commit real credentials.

Options:
  --gateways <list>  Comma-separated: ${PAYMENT_METHODS.join(', ')}
                     (default: ${DEFAULT_INIT_GATEWAYS.join(', ')})
  --out <path>       Output path (default: .env.example)
  --force            Overwrite the output file if it exists
  -h, --help         Show this help`

const HEADER = `# Nepal Payments environment template
#
# Generated by \`npay init\`. Copy this file to .env (which must never be
# committed) and fill in real credentials. \`npay gateway test <gateway>\`
# reads these variables.
#
# Never commit real secrets. See docs/security.md.`

function renderEnvTemplate(methods: readonly PaymentMethod[]): string {
  const blocks: string[] = [HEADER]
  for (const method of methods) {
    const descriptor = GATEWAY_DESCRIPTORS[method]
    const lines: string[] = [`# --- ${descriptor.title} ---`]
    for (const variable of descriptor.env) {
      if (variable.optional) lines.push(`# ${variable.description}`)
      const hint = variable.name.endsWith('_ENVIRONMENT') ? 'sandbox' : ''
      lines.push(`${variable.name}=${hint}`)
    }
    if (method === 'connectips') {
      lines.push(
        '# Convert CREDITOR.pfx first:',
        '#   npay connectips import-pfx CREDITOR.pfx --out creditor.key.pem'
      )
    }
    blocks.push(lines.join('\n'))
  }
  return `${blocks.join('\n\n')}\n`
}

interface ParsedInitArgs {
  readonly values: {
    readonly gateways?: string
    readonly out?: string
    readonly force: boolean
    readonly help: boolean
  }
}

/** `npay init`. Returns a process exit code. */
export async function runInit(
  argv: string[],
  ctx: CliContext
): Promise<number> {
  let parsed: ParsedInitArgs
  try {
    parsed = parseArgs({
      args: argv,
      allowPositionals: true,
      options: {
        gateways: { type: 'string' },
        out: { type: 'string' },
        force: { type: 'boolean', default: false },
        help: { type: 'boolean', short: 'h', default: false },
      },
    })
  } catch (error) {
    ctx.stderr(
      `npay: ${error instanceof Error ? error.message : String(error)}`
    )
    ctx.stderr(INIT_USAGE)
    return 2
  }

  if (parsed.values.help) {
    ctx.stdout(INIT_USAGE)
    return 0
  }

  const methods =
    parsed.values.gateways === undefined
      ? [...DEFAULT_INIT_GATEWAYS]
      : parseGatewayList(parsed.values.gateways)
  if (methods === undefined) {
    ctx.stderr(
      `npay: --gateways must be a comma-separated list of ${PAYMENT_METHODS.join(', ')}`
    )
    return 2
  }

  const out = parsed.values.out ?? '.env.example'
  if (!parsed.values.force && (await ctx.fileExists(out))) {
    ctx.stderr(`npay: ${out} already exists (use --force to overwrite)`)
    return 1
  }

  await ctx.writeFile(out, renderEnvTemplate(methods), 0o644)
  ctx.stdout(`Wrote ${out} for: ${methods.join(', ')}`)
  ctx.stdout(
    'Copy it to .env, fill in credentials, then run `npay gateway test`.'
  )
  return 0
}
